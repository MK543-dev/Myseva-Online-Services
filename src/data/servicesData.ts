/**
 * Generates the official WhatsApp link with exact pre-filled message format:
 * "Hi, I am interested in your product/service: Service Name. Please provide more details"
 */
export function getWhatsAppUrl(serviceName?: string): string {
  const message = serviceName
    ? `Hi, I am interested in your product/service: ${serviceName}. Please provide more details`
    : 'Hi, I am interested in MySeva Online Services. Please provide more details';
  return `https://wa.me/${CONTACT_INFO.whatsappRaw}?text=${encodeURIComponent(message)}`;
}

export function getEmailUrl(subject?: string, body?: string): string {
  const emailSub = subject ? encodeURIComponent(subject) : encodeURIComponent('Enquiry - MySeva Online Services');
  const emailBody = body ? encodeURIComponent(body) : encodeURIComponent('Hi MySeva Team,\n\nI would like to enquire about your online services.');
  return `mailto:${CONTACT_INFO.email}?subject=${emailSub}&body=${emailBody}`;
}

